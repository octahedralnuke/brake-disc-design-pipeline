"""Command-line entry point; numerical or solver failure always returns nonzero."""

import argparse
from dataclasses import asdict
import importlib
import json
import math
from pathlib import Path
import sys
from .model import Config, requirements


def main(argv=None):
    parser = argparse.ArgumentParser(prog="brakedisc", description="Kart brake disc design pipeline")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("doctor", help="Check CAD, mesher and external solver availability")
    sizing = sub.add_parser("size", help="Print analytical braking requirements")
    sizing.add_argument("--config", type=Path, default=Path("configs/kart.json"))
    run = sub.add_parser("run", help="Generate and analyse all selected designs")
    run.add_argument("--config", type=Path, default=Path("configs/kart.json"))
    run.add_argument("--out", type=Path, default=Path("results"))
    run.add_argument("--variant", action="append", help="Select one or more configured variants")
    run.add_argument("--mesh-mm", type=float)
    run.add_argument("--overwrite", action="store_true", help="Replace a directory previously generated by this tool")
    check = sub.add_parser("check", help="Re-evaluate a saved study against acceptance limits")
    check.add_argument("summary", type=Path)
    check.add_argument("--min-safety-factor", type=float)
    check.add_argument("--max-temperature", type=float)
    verification = sub.add_parser("verify", help="Run independent analytical solver benchmarks")
    verification.add_argument("--config", type=Path, default=Path("configs/kart.json"))
    verification.add_argument("--out", type=Path, default=Path("results-verification"))
    conv = sub.add_parser("converge", help="Run a three-mesh baseline sensitivity study")
    conv.add_argument("--config", type=Path, default=Path("configs/kart.json"))
    conv.add_argument("--out", type=Path, default=Path("results-convergence"))
    conv.add_argument("--sizes", type=float, nargs=3, default=[6., 5., 4.])
    args = parser.parse_args(argv)
    try:
        if args.command == "doctor":
            from .solver import find_ccx
            import subprocess
            for package in ("cadquery", "gmsh", "numpy", "matplotlib", "meshio"):
                module = importlib.import_module(package)
                print(f"{package}: {getattr(module, '__version__', 'available')}")
            executable = find_ccx()
            version = subprocess.run([executable, "-v"], capture_output=True, text=True)
            if version.returncode or "Version" not in version.stdout:
                raise RuntimeError(f"CalculiX cannot execute: {version.stderr.strip()}")
            print(f"CalculiX: {executable} ({version.stdout.strip()})")
            return 0
        if args.command == "size":
            c = Config.load(args.config)
            print(json.dumps({d.name: requirements(c.scenario, d, c.material) for d in c.variants}, indent=2))
            return 0
        if args.command == "run":
            from .pipeline import run
            study = run(args.config, args.out, args.variant, args.mesh_mm, args.overwrite)
            print(f"Report: {(args.out/'report.html').resolve()}")
            return 0 if study["passed"] else 2
        if args.command == "verify":
            from .verification import verify
            report = verify(args.config, args.out.resolve())
            print(json.dumps(report, indent=2))
            return 0 if report["passed"] else 2
        if args.command == "converge":
            from .convergence import converge
            return 0 if converge(args.config, args.out, args.sizes)["passed"] else 2
        if args.command == "check":
            return check_summary(args.summary, args.min_safety_factor, args.max_temperature)
    except (ValueError, KeyError, TypeError, OSError, RuntimeError, ImportError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


def check_summary(path, minimum=None, maximum=None):
    from .pipeline import evaluate
    from .model import Limits
    study = json.loads(path.read_text())
    if study.get("schema_version") != 1 or not study.get("results") or study.get("errors"):
        raise ValueError("Study is incomplete or contains solver errors")
    limits = dict(study["limits"])
    if minimum is not None:
        limits["min_safety_factor"] = minimum
    if maximum is not None:
        limits["max_temperature_c"] = maximum
    limits = asdict(Limits(**limits))
    passed = True
    for result in study["results"]:
        for key in ("safety_factor", "peak_temperature_c", "volume_error_fraction", "energy_error_fraction",
                    "reaction_torque_error_fraction"):
            if type(result[key]) not in (int, float) or not math.isfinite(result[key]):
                raise ValueError(f"Invalid result: {key}")
        if (result["safety_factor"] <= 0 or any(result[k] < 0 for k in (
            "volume_error_fraction", "energy_error_fraction", "reaction_torque_error_fraction"))):
            raise ValueError("Invalid result ranges")
        checks = evaluate(result, limits)
        passed &= all(checks.values())
        print(result["name"] + ": " + ", ".join(f"{k}={'PASS' if v else 'FAIL'}" for k, v in checks.items()))
    return 0 if passed else 2


if __name__ == "__main__":
    raise SystemExit(main())
